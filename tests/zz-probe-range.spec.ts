import { authenticatedTest as test } from '../src/fixtures/pages.fixture';
import { newEssSession, openMyInfoFromMenu, nextResponse } from '../src/utils/myInfo';
import { ImmigrationPage, QualificationsPage } from '../src/pages';
import { fillDate } from '../src/utils/dateInput';
test('probe ranges', async ({ page, browser, addEmployeePage }) => {
  test.setTimeout(400_000);
  const { essPage: p, close } = await newEssSession(page, browser, addEmployeePage, 'QaRangeProbe');
  const emp = await openMyInfoFromMenu(p);
  const base = `/web/index.php/api/v2/pim/employees/${emp}/`;
  const im = new ImmigrationPage(p);
  await im.goto(emp); await p.waitForLoadState('networkidle');
  await im.addButton.click(); await im.numberInput.waitFor();
  await im.numberInput.fill('PRANGE1');
  await fillDate(im.issuedDateInput, '2024-10-01', 'yyyy-dd-mm'); await fillDate(im.expiryDateInput, '2023-10-01', 'yyyy-dd-mm');
  await im.issuedDateInput.click(); await p.keyboard.press('Tab'); await p.waitForTimeout(800);
  console.log('IMM UI errs after blur', JSON.stringify(await im.fieldErrors.allInnerTexts()));
  const r1 = nextResponse(p, '/immigrations', 'POST'); await im.save(); const x1 = await r1;
  console.log('IMM UI save', x1?.status(), (await x1?.text().catch(() => ''))?.slice(0, 200), 'errs', JSON.stringify(await im.fieldErrors.allInnerTexts()));
  const a1 = await p.request.post(base + 'immigrations', { data: { number: 'PRANGE2', issuedDate: '2024-01-10', expiryDate: '2020-01-10', type: 1, status: '', reviewDate: '', comment: '' } });
  console.log('IMM API expiry<issued', a1.status(), (await a1.text()).slice(0, 200));
  const q = new QualificationsPage(p);
  await q.goto(emp); await p.waitForLoadState('networkidle');
  await q.openAddWorkExperience(); await q.companyInput.waitFor();
  await q.companyInput.fill('QaRangeCo'); await q.jobTitleInput.fill('QaT');
  await fillDate(q.fromDateInput, '2022-01-01', 'yyyy-dd-mm'); await fillDate(q.toDateInput, '2021-01-01', 'yyyy-dd-mm');
  await q.companyInput.click(); await p.waitForTimeout(800);
  console.log('WE UI errs after blur', JSON.stringify(await q.fieldErrors.allInnerTexts()));
  const r2 = nextResponse(p, '/work-experiences', 'POST'); await q.save(); const x2 = await r2;
  console.log('WE UI save', x2?.status(), (await x2?.text().catch(() => ''))?.slice(0, 200), 'errs', JSON.stringify(await q.fieldErrors.allInnerTexts()));
  const a2 = await p.request.post(base + 'work-experiences', { data: { company: 'QaRangeApi', jobTitle: 'T', fromDate: '2022-01-01', toDate: '2020-01-01', comment: '' } });
  console.log('WE API to<from', a2.status(), (await a2.text()).slice(0, 200));
  const a3 = await p.request.post(base + 'licenses', { data: { licenseId: 1, licenseNo: 'L1', issuedDate: '2024-01-01', expiryDate: '2020-01-01' } });
  console.log('LIC API expiry<issued', a3.status(), (await a3.text()).slice(0, 200));
  const lic = await p.request.get('/web/index.php/api/v2/admin/licenses?limit=1'); console.log('licenses list for ESS', lic.status(), (await lic.text()).slice(0, 120));
  await close();
});
